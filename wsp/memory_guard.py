import psutil

GiB = 1024 ** 3
SUPERVISED_SHA256 = 'd15d4b6de55f662ac40e867702d31afe738d032fa06b829b2b1a21a49d4a48ee'
SUPERVISED_PARAMETERS = 26_895_998_464


class GuardError(RuntimeError):
    pass


def supervised_permit(path):
    """Operator-created, time-limited approval record; never generated by the IDE.

    This is an auditable decision gate, not a security boundary against arbitrary
    Python. The default remains <9B; only this exact reviewed text artifact (and
    explicitly approved derived exports) can use the supervised budget.
    """
    try:
        raw = Path(path).read_bytes()
        p = json.loads(raw)
        if (p['supervised'] is not True or not isinstance(p['approval_message'], str)
                or not p['approval_message'].strip() or p['base_sha256'] != SUPERVISED_SHA256
                or p['parameters'] != SUPERVISED_PARAMETERS
                or not time.time() < p['expires'] <= time.time()+3600):
            raise ValueError('identity, presence approval or expiry is invalid')
        for key, lower, upper in [('context',1,128),('new_tokens',1,8),('budget_gib',16,26),
                                  ('ceiling_gib',16,28),('timeout',1,900)]:
            if type(p[key]) is not int or not lower <= p[key] <= upper:
                raise ValueError(f'{key} outside reviewed bounds')
        if not 0 < p['forecast_gib'] <= p['budget_gib'] <= p['ceiling_gib']:
            raise ValueError('forecast/budget ordering invalid')
        derived=p.get('derived_sha256',[])
        if not isinstance(derived,list) or any(not isinstance(h,str) or not re.fullmatch(r'[0-9a-f]{64}',h) for h in derived):
            raise ValueError('derived_sha256 must enumerate exact lowercase SHA256 hashes')
        if type(p.get('allow_derived_exports',False)) is not bool:
            raise ValueError('derived-export approval must be boolean')
    except (OSError, ValueError, KeyError, TypeError) as e:
        raise GuardError(f'Supervised permit invalid: {e}') from e
    return p, hashlib.sha256(raw).hexdigest()


def permit_matches_workspace(p, ws):
    if ws.kind != 'gguf' or ws.n_params() != p['parameters']:
        return False
    if ws.meta.get('base_sha256') == p['base_sha256']:
        return True
    if not p.get('allow_derived_exports',False):
        return False
    try:
        sidecar = json.loads(Path(str(ws.store.path)+'.json').read_text())
        return (sidecar.get('format') in ('standalone-gguf-same-scheme','standalone-gguf-mixed')
                and sidecar.get('base_sha256') == p['base_sha256']
                and sidecar.get('artifact_sha256') == ws.meta.get('base_sha256')
                and (sidecar.get('format') != 'standalone-gguf-mixed'
                     or ws.meta.get('base_sha256') in p.get('derived_sha256',[])))
    except (OSError,ValueError,TypeError):
        return False


def _command(*args):
    return subprocess.check_output(args, text=True, timeout=2)


def macos_vm_stat(raw: str, total: int) -> dict:
    """Conservative reclaimable estimate, excluding anonymous inactive pages.

    Apple's vm_stat already subtracts speculative from Mach free_count. Do not
    subtract it twice or add it separately to file-backed pages. Purgeable pages
    are recorded but deliberately receive no extra credit: this lower estimate
    avoids relying on overlap or immediate reclaimability of volatile objects.
    See docs/QUANTIZED.md for pinned Apple sources and historical qualification.
    """
    header = re.search(r'page size of (\d+) bytes', raw)
    if not header or int(header[1]) not in (4096, 16384):
        raise GuardError('Missing or malformed macOS page size')
    page = int(header[1])
    required = ('Pages free', 'Pages inactive', 'Pages speculative',
                'File-backed pages', 'Pages purgeable',
                'Pages occupied by compressor', 'Swapouts')
    counters = {}
    for name in required:
        matches = re.findall(r'^"?' + re.escape(name) + r'"?:([^\n]*)$', raw, re.M)
        value = re.fullmatch(r'\s*(\d+)\.\s*', matches[0]) if len(matches) == 1 else None
        if value is None:
            raise GuardError(f'Missing, malformed or duplicate macOS counter: {name}')
        counters[name] = int(value[1]) * page
        if name != 'Swapouts' and counters[name] > total:
            raise GuardError(f'Impossible macOS counter: {name}')
    available = counters['Pages free'] + counters['File-backed pages']
    if available <= 0 or available > total:
        raise GuardError('Impossible macOS available memory')
    return dict(available=available, free=counters['Pages free'],
                inactive=counters['Pages inactive'], speculative=counters['Pages speculative'],
                purgeable=counters['Pages purgeable'], file_backed=counters['File-backed pages'],
                reclaimable=counters['File-backed pages'],
                compressed=counters['Pages occupied by compressor'], swap_out=counters['Swapouts'],
                available_estimator='vm_stat.free_excluding_speculative + file_backed; purgeable credit=0')


def snapshot() -> dict:
    """Availability includes reclaimable memory; never treat free percentage as headroom."""
    vm, swap = psutil.virtual_memory(), psutil.swap_memory()
    s = dict(time=time.time(), available=int(vm.available), free=int(vm.free), total=int(vm.total),
             swap_used=int(swap.used), swap_out=int(swap.sout), compressed=0, pressure=0)
    if platform.system() == 'Darwin':
        s['psutil_available'] = s['available']  # diagnostic only; inactive includes anonymous memory
        s.update(macos_vm_stat(_command('/usr/bin/vm_stat'), s['total']))
        s['pressure'] = int(_command('/usr/sbin/sysctl', '-n', 'kern.memorystatus_vm_pressure_level').strip())
        s['vm_pressure'] = int(_command('/usr/sbin/sysctl', '-n', 'vm.memory_pressure').strip())
        # XNU kern_memorystatus_notify.c maps the internal enum to dispatch bits:
        # 1 NORMAL, 2 WARN, 4 CRITICAL. vm.memory_pressure is pageout activity
        # (vm_pageout.c: freed_* counters), NOT a warning level.
        if s['pressure'] not in (1, 2, 4):
            raise GuardError(f"Ambiguous macOS pressure value: {s['pressure']}")
    elif platform.system() == 'Linux':
        info = Path('/proc/meminfo').read_text()
        match = re.search(r'^MemAvailable:\s+(\d+) kB', info, re.M)
        if not match:
            raise GuardError('Missing MemAvailable telemetry')
        s['available'] = int(match[1]) * 1024
        s['reclaimable'] = int(getattr(vm, 'cached', 0))
        psi = Path('/proc/pressure/memory').read_text()
        full = re.search(r'full avg10=([\d.]+)', psi)
        if not full:
            raise GuardError('Missing Linux memory PSI')
        s['pressure'] = 2 if float(full[1]) > 0.1 else 1
    else:
        raise GuardError('Memory telemetry is unsupported on this OS')
    if s['available'] <= 0:
        raise GuardError('Available memory is unknown')
    return s


class _RUsage(ctypes.Structure):
    _fields_ = [('uuid', ctypes.c_uint8 * 16)] + [(n, ctypes.c_uint64) for n in
        ('user', 'system', 'pkg', 'interrupt', 'pageins', 'wired', 'resident', 'footprint',
         'start', 'exit', 'child_user', 'child_system', 'child_pkg', 'child_interrupt',
         'child_pageins', 'child_elapsed', 'diskread', 'diskwrite')]


def process_memory(pid: int) -> dict:
    root = psutil.Process(pid)
    processes = [root] + root.children(recursive=True)
    rss = footprint = 0
    live = []
    identities = {}
    for p in processes:
        try:
            rss += p.memory_info().rss
            if platform.system() == 'Darwin':
                data = _RUsage()
                lib = ctypes.CDLL('/usr/lib/libproc.dylib')
                if lib.proc_pid_rusage(p.pid, 2, ctypes.byref(data)) != 0:
                    raise GuardError(f'Missing physical-footprint telemetry for pid {p.pid}')
                footprint += data.footprint
            else:
                footprint += p.memory_info().rss
            live.append(p.pid)
            identities[p.pid] = p.create_time()
        except psutil.NoSuchProcess:
            continue
    return dict(tree_rss=rss, tree_footprint=footprint, pids=live, identities=identities)


@dataclass(frozen=True)
class Policy:
    floor: int = 20 * GiB
    preferred: int = 25 * GiB
    budget: int = 16 * GiB
    ceiling: int = 24 * GiB
    swap_growth: int = 64 * 1024 ** 2
    compression_growth: int = GiB

    def preflight(self, sample, forecast):
        if not isinstance(sample.get('available'), int) or sample['available'] <= 0:
            raise GuardError('Unknown available memory; refusing load')
        if sample.get('pressure') != 1:
            raise GuardError('Memory pressure is not normal')
        if not 0 < forecast <= min(self.budget, self.ceiling):
            raise GuardError('Forecast exceeds the conservative incremental memory budget')
        if sample['available'] - forecast < self.preferred:
            raise GuardError(f'Forecast leaves less than {self.preferred/GiB:g} GiB available headroom')

    def violation(self, current, baseline, previous=None):
        if current.get('pressure') != 1:
            return 'memory pressure warning'
        if current.get('available', 0) < self.floor:
            return f'available headroom below {self.floor/GiB:g} GiB'
        gpu = current.get('gpu',{})
        if gpu.get('active') and gpu.get('backend') == 'metal' and (
                not isinstance(gpu.get('metal_allocated'),int) or not isinstance(gpu.get('metal_recommended'),int)):
            return 'Metal allocation telemetry missing'
        if max(current.get('tree_rss', 0), current.get('tree_footprint', 0),
               gpu.get('metal_allocated',0) or 0, gpu.get('mps_driver',0) or 0) > min(self.budget, self.ceiling):
            return 'process-tree memory exceeds budget'
        if current['swap_used'] - baseline['swap_used'] > self.swap_growth or current['swap_out'] - baseline['swap_out'] > self.swap_growth:
            return 'material swap growth'
        if current['compressed'] - baseline['compressed'] > self.compression_growth:
            return 'material compression growth'
        if previous and current['tree_footprint'] - previous['tree_footprint'] > 4 * GiB:
            return 'runaway process growth (>4 GiB per sample)'
        return None


def forecast(ws, context=512, operation='legacy') -> dict:
    """Conservative, itemised bytes, includes mapped weights as resident + temporary copies."""
    if operation != 'legacy':
        from .capacity import context_limit
        context = context_limit(context, getattr(ws.struct,'n_ctx',None))
    c = ws.hf_config.get('text_config', ws.hf_config)
    hidden = int(c.get('hidden_size', ws.struct.d_model or 1024))
    layers = int(c.get('num_hidden_layers', ws.struct.n_layers or 32))
    vocab = int(c.get('vocab_size', ws.struct.d_vocab or 160000))
    if ws.kind == 'gguf':
        weights = ws.store.nbytes()
    elif ws.kind == 'hf':
        # The tensors the runner loads (not a vision tower or MTP head it skips), at the run dtype's element size.
        import torch
        from .runtime_layouts import loaded_params
        weights = loaded_params(ws) * torch.empty((), dtype=getattr(torch, os.environ.get('WSP_RUN_DTYPE', 'float32'))).element_size()
    else:
        weights = ws.n_params() * 4
    patch = (ws.patch_stored if hasattr(ws,'patch_stored') else sum(p.stored if hasattr(p,'stored') else p.meta()['stored'] for p in ws.patches))*4
    from .memory_forecast import estimate
    hybrid = None
    if c.get('model_type') == 'qwen3_5_text':
        hybrid = (int(c['linear_num_value_heads']),int(c['linear_key_head_dim']),
                  int(c['linear_value_head_dim']),int(c['linear_num_key_heads']),int(c['linear_conv_kernel_dim']))
    heads = c.get('num_attention_heads', getattr(ws.struct,'n_heads',None))
    full = None
    if hybrid:
        if c.get('layer_types'):
            full = c['layer_types'].count('full_attention')
        elif hasattr(ws, 'names'):
            full = sum(name.endswith('.self_attn.q_proj.weight') for name in ws.names())
    return estimate(weights,context,hidden,layers,vocab,patch,hybrid,heads=heads,
                    operation=operation, kv_heads=c.get('num_key_value_heads'), head_dim=c.get('head_dim'),
                    attention_layers=full, intermediate=c.get('intermediate_size'))



def require_lease(ws, loading=False):
    if loading and getattr(ws, '_metadata_only', False) and getattr(ws, '_runtime_client', None) is None:
        raise GuardError('Metadata-only workspace cannot load a runner; reopen with base identity verification')
    runtime = getattr(ws, '_runtime_client', None)
    if runtime is not None:
        return runtime.require(ws, loading=loading)
    path = os.environ.get('WSP_GUARD_LEASE')
    if not path:
        raise GuardError('GGUF inference requires the external memory watchdog. See docs/QUANTIZED.md.')
    try:
        lease = json.loads(Path(path).read_text())
        if time.time() - lease['time'] > 5 or lease['pgid'] != os.getpgrp() or not lease['ok']:
            raise ValueError('expired or wrong process group')
    except (OSError, ValueError, KeyError) as e:
        raise GuardError(f'Watchdog lease is invalid: {e}') from e
    policy, context = Policy(), 512
    if not 0 < ws.n_params() < 9_000_000_000:
        permit_path = os.environ.get('WSP_SUPERVISED_PERMIT')
        if not permit_path:
            raise GuardError('Guarded tests require verified total parameter count strictly below 9B; supervised approval required')
        permit, digest = supervised_permit(permit_path)
        if digest != lease.get('supervised_permit_sha256') or not permit_matches_workspace(permit,ws):
            raise GuardError('Supervised approval does not cover this workspace or lease')
        policy = supervised_policy(permit)
        context = permit['context']
    required = forecast(ws,context)['total']
    if required > lease.get('forecast_bytes',0):
        raise GuardError('Model forecast exceeds the watchdog reservation')
    current = snapshot()
    if loading:
        policy.preflight(current, required)
    elif current.get('pressure') != 1 or current.get('available',0) < policy.floor:
        raise GuardError('Live headroom/pressure is unsafe')
    # Resident weights are already reflected in live telemetry. Subtracting the
    # full forecast again on every token would double-count the active model.


def gpu_metrics() -> dict:
    """Called in the runner, where MPS allocator metrics describe the actual process."""
    import torch
    if torch.backends.mps.is_available():
        return dict(mps_current=torch.mps.current_allocated_memory(), mps_driver=torch.mps.driver_allocated_memory(),
                    mps_recommended=torch.mps.recommended_max_memory())
    return dict(mps_current=None, mps_driver=None, mps_recommended=None)


def supervised_policy(permit):
    # The supervised large-model request requires no swap/compressor growth,
    # stricter than the historical small-test material-growth thresholds.
    return Policy(budget=permit['budget_gib']*GiB,ceiling=permit['ceiling_gib']*GiB,
                  swap_growth=0,compression_growth=0)


def stage(name, timeout=None):
    """Publish an optional shorter deadline for the external watchdog."""
    path = Path(os.environ['WSP_GUARD_TELEMETRY']+'.stage.json')
    value = dict(name=name, deadline=time.monotonic()+timeout if timeout is not None else None)
    temporary = path.with_suffix('.tmp')
    temporary.write_text(json.dumps(value)); temporary.replace(path)


def check_stage(value, now):
    if not isinstance(value,dict) or not isinstance(value.get('name'),str):
        raise GuardError('Malformed stage telemetry')
    deadline=value.get('deadline')
    if deadline is not None:
        if type(deadline) not in (int,float) or not math.isfinite(deadline):
            raise GuardError('Malformed stage deadline')
        if now > deadline:
            raise GuardError(f"Stage wall-clock timeout: {value['name']}")


def owned_remaining(known, errors):
    """Unknown identity/liveness is unresolved, never evidence of termination."""
    remaining = []
    for pid, born in known.items():
        try:
            p = psutil.Process(pid)
            if p.create_time() == born and p.status() != psutil.STATUS_ZOMBIE:
                remaining.append(pid)
        except psutil.NoSuchProcess:
            pass
        except Exception as exc:
            errors.append(dict(operation='verify', pid=pid, error=repr(exc)))
            remaining.append(pid)
    return remaining


def _attempt(errors, operation, pid, fn):
    try:
        return fn()
    except (ProcessLookupError, psutil.NoSuchProcess):
        pass
    except Exception as exc:
        errors.append(dict(operation=operation, pid=pid, error=repr(exc)))


def _discover(known, errors):
    # Capture descendants before signalling, including children in separate groups.
    for pid, born in list(known.items()):
        def discover():
            p = psutil.Process(pid)
            if p.create_time() == born:
                for descendant in p.children(recursive=True):
                    known.setdefault(descendant.pid, descendant.create_time())
        _attempt(errors, 'discover descendants', pid, discover)


def _group_signal(child, known, errors, sig):
    # A departed/recycled group leader is not by itself authority to signal
    # its old PGID. Require a still-live known identity in that group.
    for pid, born in list(known.items()):
        try:
            p = psutil.Process(pid)
            if p.create_time() == born and p.status() != psutil.STATUS_ZOMBIE and os.getpgid(pid) == child.pid:
                _attempt(errors, 'killpg '+str(sig), child.pid, lambda: os.killpg(child.pid, sig))
                return
        except (ProcessLookupError, psutil.NoSuchProcess):
            pass
        except Exception as exc:
            errors.append(dict(operation='verify group', pid=pid, error=repr(exc)))


def _identity_signal(known, errors, sig):
    for pid, born in list(known.items()):
        def send():
            p = psutil.Process(pid)
            if p.create_time() == born:
                p.send_signal(sig)  # psutil also checks PID reuse
        _attempt(errors, 'signal '+str(sig), pid, send)


def kill_group(child, known, errors=None, sig=signal.SIGKILL):
    """One signal to a verified owned process group and its verified identities.

    Never waits and never reaps: the caller polls ``child`` from its own loop.
    """
    errors = errors if errors is not None else []
    _discover(known, errors)
    _group_signal(child, known, errors, sig)
    _identity_signal(known, errors, sig)
    return errors


def stop_group(child, known, errors=None):
    """Terminate only verified owned identities; preserve every cleanup error."""
    errors = errors if errors is not None else []
    _discover(known, errors)
    _group_signal(child, known, errors, signal.SIGTERM)
    _identity_signal(known, errors, signal.SIGTERM)
    try:
        child.wait(timeout=3)
    except subprocess.TimeoutExpired:
        pass
    except Exception as exc:
        errors.append(dict(operation='wait after TERM', pid=child.pid, error=repr(exc)))
    _group_signal(child, known, errors, signal.SIGKILL)
    _identity_signal(known, errors, signal.SIGKILL)
    deadline = time.monotonic()+3
    while time.monotonic() < deadline:
        if not owned_remaining(known, errors):
            break
        time.sleep(.05)
    _attempt(errors, 'reap', child.pid, lambda: child.wait(timeout=3))
    return owned_remaining(known, errors)


def supervise(command, log, forecast_bytes, timeout=600, policy=None, permit_path=None):
    policy = policy or Policy()
    permit, permit_sha = None, None
    if permit_path:
        permit, permit_sha = supervised_permit(permit_path)
        if forecast_bytes != int(permit['forecast_gib']*GiB) or timeout != permit['timeout']:
            raise GuardError('Invocation forecast/timeout differs from supervised approval')
        policy = supervised_policy(permit)
    log = Path(log)
    log.parent.mkdir(parents=True, exist_ok=True)
    latch = log.parent / 'GUARD_FAILED.json'
    if latch.exists():
        raise GuardError(f'Previous guard failure is latched at {latch}; investigate before another load')
    baseline = None
    try:
        baseline = snapshot()
        policy.preflight(baseline, forecast_bytes)
    except Exception as exc:
        refusal = dict(event='preflight_refused',baseline=baseline,forecast=forecast_bytes,
                       policy=asdict(policy),reason=f'{type(exc).__name__}: {exc}',child_spawned=False)
        log.write_text(json.dumps(refusal)+'\n')
        latch.write_text(json.dumps(refusal,indent=2))
        raise
    lease_path = log.with_suffix('.lease.json')
    env = {**os.environ, 'WSP_GUARD_LEASE': str(lease_path), 'WSP_GUARD_TELEMETRY': str(log),
           'WSP_MAX_CTX': '512', 'WSP_MAX_NEW_TOKENS': '64', 'TOKENIZERS_PARALLELISM': 'false'}
    env.pop('WSP_SUPERVISED_PERMIT',None)  # inherited state never releases a new gate
    if permit:
        env.update(WSP_SUPERVISED_PERMIT=str(Path(permit_path).resolve()),
                   WSP_MAX_CTX=str(permit['context']),WSP_MAX_NEW_TOKENS=str(permit['new_tokens']))
    # A startup handshake ensures the first load cannot race the lease.
    gate = ['-c', 'import os,time,pathlib,sys; p=pathlib.Path(os.environ["WSP_GUARD_LEASE"]); '
            '\nfor _ in range(100):\n if p.exists(): break\n time.sleep(.05)\n'
            'os.execvpe(sys.argv[1],sys.argv[1:],os.environ)']
    child = subprocess.Popen([sys.executable, *gate, *command], env=env, start_new_session=True)
    known, previous, reason = {child.pid: psutil.Process(child.pid).create_time()}, None, None
    start = time.monotonic()
    try:
        with log.open('w') as f:
            f.write(json.dumps(dict(event='preflight', baseline=baseline, forecast=forecast_bytes,
                                    policy=asdict(policy), command=command, pid=child.pid,
                                    supervised_permit=permit,supervised_permit_sha256=permit_sha))+'\n')
            f.flush()
            while child.poll() is None:
                try:
                    if permit and supervised_permit(permit_path)[1] != permit_sha:
                        raise GuardError('Supervised approval changed or was revoked')
                    current = {**snapshot(), **process_memory(child.pid)}
                    known.update(current['identities'])
                    gpu_path = Path(str(log)+'.gpu.json')
                    if gpu_path.exists():
                        gpu = json.loads(gpu_path.read_text())
                        if gpu.get('error') or (gpu.get('active') and time.time()-gpu['time'] > 3):
                            raise GuardError('Runner GPU telemetry lost or stale')
                        current['gpu'] = gpu
                    reason = policy.violation(current, baseline, previous)
                    stage_path = Path(str(log)+'.stage.json')
                    if stage_path.exists():
                        current['stage'] = json.loads(stage_path.read_text())
                        check_stage(current['stage'],time.monotonic())
                    if time.monotonic()-start > timeout:
                        reason = 'wall-clock timeout'
                    f.write(json.dumps(dict(event='sample', **current))+'\n')
                    f.flush()
                    if reason:
                        break
                    tmp = lease_path.with_suffix('.tmp')
                    tmp.write_text(json.dumps(dict(time=time.time(), pgid=child.pid, ok=True,
                                                   supervised_permit_sha256=permit_sha,
                                                   forecast_bytes=forecast_bytes)))
                    tmp.replace(lease_path)
                    previous = current
                except Exception as e:
                    reason = f'telemetry lost: {type(e).__name__}: {e}'
                    break
                time.sleep(1)
    except BaseException:
        reason = 'supervisor interrupted'
        raise
    finally:
        lease_path.unlink(missing_ok=True)
        cleanup_errors = []
        try:
            remaining = stop_group(child, known, cleanup_errors)
        except Exception as exc:
            # Even an unexpected cleanup implementation error must not suppress
            # the teardown record/failure latch or imply the process tree exited.
            cleanup_errors.append(dict(operation='stop_group', error=repr(exc)))
            remaining = owned_remaining(known, cleanup_errors)
        if cleanup_errors and reason is None:
            reason = 'cleanup error; inspect teardown evidence'
        outcome = dict(event='teardown', reason=reason, returncode=child.returncode,
                       remaining=remaining, cleanup_errors=cleanup_errors,
                       cleanup_complete=not remaining, elapsed=time.monotonic()-start)
        with log.open('a') as f:
            f.write(json.dumps(outcome)+'\n')
        if reason or remaining or child.returncode:
            latch.write_text(json.dumps(outcome, indent=2))
    if reason or remaining or child.returncode:
        raise GuardError(f'Guarded run failed: {outcome}')
    return outcome


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--log', required=True)
    p.add_argument('--forecast-gib', type=float, required=True)
    p.add_argument('--timeout', type=int, default=600)
    p.add_argument('--supervised-permit', help='Operator-created approval after supervised decision gate only')
    p.add_argument('--zero-growth',action='store_true',help='Stop on any swap/compressor growth')
    p.add_argument('command', nargs=argparse.REMAINDER)
    a = p.parse_args()
    cmd = a.command[1:] if a.command[:1] == ['--'] else a.command
    if not cmd:
        p.error('a child command is required')
    print(json.dumps(supervise(cmd, a.log, int(a.forecast_gib*GiB), a.timeout,
                               permit_path=a.supervised_permit,
                               policy=Policy(swap_growth=0,compression_growth=0) if a.zero_growth else None), indent=2))


if __name__ == '__main__':
    main()
