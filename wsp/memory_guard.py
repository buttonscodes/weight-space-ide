"""Fail-closed memory preflight and external process-group watchdog.

Run before ANY real test load: python -m wsp.memory_guard --log /outside/repo/run.jsonl
--forecast-gib 6 --timeout 600 -- python scripts/quantized_e2e.py ...
The child gets a short-lived lease. A failed run leaves a latch beside the log; an
operator must investigate before selecting a new run. Only our new process group is stopped.
"""
from __future__ import annotations

